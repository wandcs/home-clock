"""Rebuild the versioned 4s PCM; check its frozen WAV and emit portable C ROM."""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import io
import json
import struct
import wave

ROOT = Path(__file__).resolve().parents[2]
ASSET = ROOT / 'assets/alarm-audio'
SOURCE = ROOT / 'firmware/features/alarm-audio/alarm_reference.c'


def build():
    path = ROOT / 'tools/alarm-audio/synthesize.py'
    spec = importlib.util.spec_from_file_location('reviewed_alarm', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    payload = module.pcm(module.reference())
    memory = io.BytesIO()
    with wave.open(memory, 'wb') as wav:
        wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(22050)
        wav.writeframes(payload)
    version = module.SPEC['version']
    frozen = module.SPEC['reference_wav_sha256']
    assert hashlib.sha256(memory.getvalue()).hexdigest() == frozen, 'versioned candidate WAV changed'
    values = struct.unpack('<88200h', payload)
    text = '#include "alarm_audio.h"\n/* Generated by tools/alarm-audio/generate.py; original synthesis, ' + version + '. */\n'
    text += 'const int16_t aa_reference[AA_PERIOD] = {\n'
    text += ''.join('    ' + ','.join(map(str, values[i:i+16])) + ',\n'
                    for i in range(0, len(values), 16))
    text += '};\n'
    manifest = {
        'version': version, 'status': module.SPEC['status'], 'source': 'original mathematical synthesis',
        'license': 'Original synthesis under the project MIT License; no third-party samples',
        'format': 'mono 22050Hz s16le', 'frames': len(values), 'bytes': len(payload),
        'pcm_sha256': hashlib.sha256(payload).hexdigest(),
        'generator_sha256_lf': hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest(),
        'spec_sha256_lf': hashlib.sha256((ASSET/'candidate.json').read_bytes().replace(b'\r\n', b'\n')).hexdigest(),
        'peak': max(map(abs, values)), 'calibration_K': None,
        'reference_wav_sha256': frozen,
    }
    return payload, text, json.dumps(manifest, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pcm, source, manifest = build()
    files = {ASSET/'reference-4s.pcm': pcm, SOURCE: source.encode(),
             ASSET/'manifest.json': manifest.encode()}
    for path, data in files.items():
        if args.check:
            assert path.read_bytes().replace(b'\r\n', b'\n') == data if path.suffix != '.pcm' else path.read_bytes() == data, path
        else:
            path.write_bytes(data)
    print(manifest, end='')
