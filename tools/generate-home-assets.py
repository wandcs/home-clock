"""Build only N8 home assets; Python 3.12/Pillow 12.3.0, existing pinned Noto.

The accepted clock A8 and N7 colon are resampled once offline, never at draw time.
Other small font subsets are rasterized directly at their target sizes. Existing
fonts and the location catalog remain byte-identical. See SIL OFL in assets.
"""
from pathlib import Path
import argparse, hashlib, json, math, re
from PIL import Image, ImageDraw, ImageFont, __version__
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/application'
FONT_SHA='2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'
CLOCK_SHA='01a444d077d1ca8201b1894d1ae0510ca1d31eb24c5ad5058270090bb2d7f84d'
# N8-R4: user-approved optical alignment, not a geometric bug correction.
CLOCK_OPTICAL_DOWN_PX={'5':2}
HEAD='时间尚未校准天气正在获取暂不可用当前已过期待设置位置尚未联网更新失败离线缓存未知晴多云阴雾雨雪雷室内明天星期日一二三四五六周'
NOTES='天气暂不可用今天高低温设置位置等待校时正在获取尚未联网当前已过期更新失败离线缓存风级舒适待判断偏热冷干湿温湿度样例～'
def sha(data):return hashlib.sha256(data).hexdigest()
def rows(data):return ',\n'.join(','.join(map(str,data[i:i+32])) for i in range(0,len(data),32))
def font_source(name,codes,glyphs,bitmap,line,base,fallback=False):
 desc=[]
 for at,adv,w,h,x,y in glyphs:
  desc.append(f'{{.bitmap_index={at},.adv_w={adv},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}}}')
 cp=','.join(str(c-codes[0]) for c in codes)
 fb=',.fallback=&clock_font_28' if fallback else ''
 return f'''static const uint8_t f{name}_bitmap[]={{\n{rows(bitmap)}\n}};
static const lv_font_fmt_txt_glyph_dsc_t f{name}_glyphs[]={{ {{0}},{','.join(desc)} }};
static const uint16_t f{name}_codes[]={{ {cp} }};
static const lv_font_fmt_txt_cmap_t f{name}_map={{.range_start={codes[0]},.range_length={codes[-1]-codes[0]+1},.glyph_id_start=1,.unicode_list=f{name}_codes,.list_length={len(codes)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};
static const lv_font_fmt_txt_dsc_t f{name}_dsc={{.glyph_bitmap=f{name}_bitmap,.glyph_dsc=f{name}_glyphs,.cmaps=&f{name}_map,.cmap_num=1,.bpp=8,.stride=1,.bitmap_format=0}};
const lv_font_t clock_home_font_{name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={line},.base_line={base},.static_bitmap=1{fb},.dsc=&f{name}_dsc}};
'''
def generate():
 assert __version__=='12.3.0','Use the pinned Pillow 12.3.0 rasterizer'
 font_path=ROOT/'.local/b2-assets/NotoSansCJKsc-Regular.otf'
 assert sha(font_path.read_bytes())==FONT_SHA,'Pinned Noto source missing or changed'
 source=(ASSETS/'font_240.c').read_bytes()
 assert sha(source)==CLOCK_SHA,'Frozen N7 clock source changed'
 text=source.decode()
 alpha=bytes(map(int,re.findall(r'\d+',re.search(r'bitmap\[\]=\{(.*?)\};',text,re.S)[1])))
 descriptors=[tuple(map(int,r)) for r in re.findall(r'\.bitmap_index=(\d+),\.adv_w=(\d+),\.box_w=(\d+),\.box_h=(\d+),\.ofs_x=(-?\d+),\.ofs_y=(-?\d+)',text)]
 assert len(descriptors)==12 and descriptors[-1][-1]==21
 c=['/* Generated by tools/generate-home-assets.py. Noto Sans CJK SC Regular, SIL OFL 1.1.\n * Existing fonts unchanged; static A8, no runtime expansion. */\n#include "home_assets.h"\nextern const lv_font_t clock_font_28;\n']
 metrics={};bitmap=bytearray();glyphs=[];scale=1.35
 for ch,(at,adv,w,h,x,y) in zip('-0123456789:',descriptors):
  nw,nh=round(w*scale),round(h*scale)
  img=Image.frombytes('L',(w,h),alpha[at:at+w*h]).resize((nw,nh),Image.Resampling.LANCZOS)
  glyphs.append((len(bitmap),round(adv*scale),nw,nh,round(x*scale),round(y*scale)-CLOCK_OPTICAL_DOWN_PX.get(ch,0)))
  bitmap.extend(img.tobytes())
 codes=list(map(ord,'-0123456789:'))
 c.append(font_source('324',codes,glyphs,bitmap,round(349*scale),round(70*scale)))
 metrics['324']={'bitmap_bytes':len(bitmap),'glyphs':len(codes),'clock_scale':scale,'colon_ofs_y':glyphs[-1][-1],'zero_box_height':glyphs[1][3],'nominal_hhmm_advance':(glyphs[1][1]*4+glyphs[-1][1])/16,'optical_adjustment':{'glyph':'5','shift_down_px':CLOCK_OPTICAL_DOWN_PX['5'],'base_scaled_ofs_y':round(descriptors[6][-1]*scale),'final_ofs_y':glyphs[6][-1],'reason':'N8-R4 user-approved optical alignment, not a geometric positioning bug'}}
 for size,subset in [(64,'-0123456789'),(46,'.0123456789'),(34,'°C%'),(32,''.join(chr(i) for i in range(32,127))+HEAD+'·°'),(30,''.join(chr(i) for i in range(32,127))+NOTES+'·°')]:
  font=ImageFont.truetype(str(font_path),size);ascent,descent=font.getmetrics();codes=sorted(set(map(ord,subset)));bitmap=bytearray();glyphs=[]
  for cp in codes:
   ch=chr(cp);x0,y0,x1,y1=font.getbbox(ch,anchor='ls');w,h=x1-x0,y1-y0
   image=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(image).text((-x0,-y0),ch,font=font,fill=255,anchor='ls')
   glyphs.append((len(bitmap),round(font.getlength(ch)*16),w,h,x0,-y1))
   if w*h:bitmap.extend(image.tobytes())
  c.append(font_source(str(size),codes,glyphs,bitmap,ascent+descent,descent,size in (30,32)))
  metrics[str(size)]={'bitmap_bytes':len(bitmap),'glyphs':len(codes),'line_height':ascent+descent,'base_line':descent}
 icons=['cloudunknown','sunny','cloudy','overcast','fog','rain','snow','thunder']
 icon_source=(ASSETS/'weather_forecast_icons.c').read_bytes();icon_text=icon_source.decode()
 for name in icons:
  raw=bytes(map(int,re.findall(r'\d+',re.search(r'static const uint8_t '+name+r'_alpha\[6400\]=\{(.*?)\};',icon_text,re.S)[1])))
  assert len(raw)==6400
  data=Image.frombytes('L',(80,80),raw).resize((60,60),Image.Resampling.LANCZOS).tobytes()
  c.append(f'static const uint8_t home_{name}_alpha[3600]={{\n{rows(data)}\n}};\nconst lv_image_dsc_t weather_home_{name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=60,.h=60,.stride=60}},.data_size=3600,.data=home_{name}_alpha}};\n')
 # Same two fixed circular arcs as N8's moon outline; supersampled once.
 # SVG: M20 15A9 9 0 0 1 9 3a9 9 0 1 0 11 12Z, stroke 1.7, round joins.
 def arc(start,end,large,sweep):
  x,y=(start[0]-end[0])/2,(start[1]-end[1])/2
  k=math.sqrt((81-x*x-y*y)/(x*x+y*y))*(-1 if large==sweep else 1)
  cx=(start[0]+end[0])/2+k*y;cy=(start[1]+end[1])/2-k*x
  a=math.atan2(start[1]-cy,start[0]-cx);b=math.atan2(end[1]-cy,end[0]-cx);delta=b-a
  if sweep and delta<0:delta+=2*math.pi
  if not sweep and delta>0:delta-=2*math.pi
  return [(cx+9*math.cos(a+delta*i/96),cy+9*math.sin(a+delta*i/96)) for i in range(97)]
 points=arc((20,15),(9,3),False,True)+arc((9,3),(20,15),True,False)[1:]
 moon=Image.new('L',(240,240));draw=ImageDraw.Draw(moon)
 draw.line([(x*10,y*10) for x,y in points],fill=255,width=17,joint='curve')
 for x,y in ((20,15),(9,3)):draw.ellipse((x*10-8.5,y*10-8.5,x*10+8.5,y*10+8.5),fill=255)
 data=moon.resize((60,60),Image.Resampling.LANCZOS).tobytes()
 c.append(f'static const uint8_t home_moon_alpha[3600]={{\n{rows(data)}\n}};\nconst lv_image_dsc_t weather_home_moon={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=60,.h=60,.stride=60}},.data_size=3600,.data=home_moon_alpha}};\n')
 icons.append('moon')
 header='#ifndef CLOCK_HOME_ASSETS_H\n#define CLOCK_HOME_ASSETS_H\n#include "lvgl.h"\n/* N8 home-only sizes; other screens retain their existing fonts. */\n'
 header+='extern const lv_font_t '+','.join('clock_home_font_'+n for n in ('324','64','46','34','32','30'))+';\n'
 header+='extern const lv_image_dsc_t '+','.join('weather_home_'+n for n in icons)+';\n#endif\n'
 output={'home_assets.c':''.join(c).encode(),'home_assets.h':header.encode()}
 record={'version':'N8-R4','font_source':'Noto Sans CJK SC Regular','font_source_sha256':FONT_SHA,'font_license':'SIL OFL 1.1; see OFL.txt and NotoSans-LICENSE.txt','font_url':'https://raw.githubusercontent.com/googlefonts/noto-cjk/main/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf','pillow':__version__,'frozen_clock_source_sha256':CLOCK_SHA,'clock_method':'offline once LANCZOS resample of accepted static A8 and N7 colon, factor 1.35; no runtime scaling','weather_source_sha256':sha(icon_source),'weather_method':'existing native 80px A8 masks downsampled once to 60px; moon is N8 two-arc outline rasterized offline at 4x then downsampled','fonts':metrics,'weather_bitmap_bytes':len(icons)*3600,'total_bitmap_bytes':sum(m['bitmap_bytes'] for m in metrics.values())+len(icons)*3600,'outputs':{name:{'bytes':len(data),'sha256':sha(data)} for name,data in output.items()}}
 output['home-assets.json']=(json.dumps(record,indent=2)+'\n').encode()
 return output,record

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 output,record=generate()
 for name,data in output.items():
  path=ASSETS/name
  if args.check:assert path.read_bytes()==data,'Generated asset drift: '+name
  elif not path.exists() or path.read_bytes()!=data:path.write_bytes(data)
 path=ASSETS/'manifest.json';manifest=json.loads(path.read_text(encoding='utf8'))
 for name,data in output.items():
  entry={'bytes':len(data),'sha256':sha(data)}
  if args.check:assert manifest.get(name)==entry,'Manifest drift: '+name
  else:manifest[name]=entry
 if not args.check:path.write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8',newline='\n')
 print(json.dumps({'checked':args.check,'total_bitmap_bytes':record['total_bitmap_bytes'],'fonts':record['fonts']},indent=2))
if __name__=='__main__':main()
