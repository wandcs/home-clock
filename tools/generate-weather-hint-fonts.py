"""Generate S20's missing 24/28/30px hint glyphs without rewriting old assets.

Use the existing fixed Noto source and Pillow 12.3.0. --check is read-only.
24px retains A4 and 30px retains A8; 28px owns no glyphs at present.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
from PIL import Image, ImageDraw, ImageFont, __version__ as PILLOW

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/application'
GENERATOR = 'tools/generate-weather-hint-fonts.py'
FONT_PATH = '.local/b2-assets/NotoSansCJKsc-Regular.otf'
FONT_SHA = '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'
OUTPUT_NAMES = ('weather_hint_fonts.c', 'weather_hint_fonts.h', 'weather_hint_fonts.json')
SOURCE_TEXT = ('MET未来完整日采样温度范围，并非标准日高低温；今天不完整不补。'
               '空气欠佳：CAMS全球模型，美标AQI>100提示，非本地测量或官方预警。'
               '每3小时取数，独立有效期4小时，当前小时有效。逐日来源与取得状态')
SPECS = {
    24: {'fallback': 'clock_font_weather_24', 'file': 'font_weather_24.c',
         'map': 'cmap', 'codes': 'unicode_list', 'bpp': 4,
         'texts': ['风17级', '阵风17级', '雨较强', '冻雨', '雪较强', '雷电', '冰雹', 'UV 强', '100%', '—']},
    28: {'fallback': 'clock_font_28', 'file': 'font_28.c',
         'map': 'cmap', 'codes': 'unicode_list', 'bpp': 4,
         'texts': ['约-5～8°', '参考温区', SOURCE_TEXT]},
    30: {'fallback': 'clock_home_font_30', 'file': 'home_assets.c',
         'map': 'f30_map', 'codes': 'f30_codes', 'bpp': 8,
         'texts': ['风17级', '阵风17级', '雨较强', '冻雨', '雪较强', '雷电', '冰雹', '空气欠佳', '约-5～8°']},
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def fallback_data(spec):
    data = (ASSETS / spec['file']).read_bytes()
    source = data.decode('utf8')
    cmap = re.search(r'\b' + spec['map'] + r'\s*=\s*\{(.*?)\};', source, re.S).group(1)
    start = int(re.search(r'\.range_start=(\d+)', cmap).group(1))
    declared = int(re.search(r'\.list_length=(\d+)', cmap).group(1))
    assert 'LV_FONT_FMT_TXT_CMAP_SPARSE_TINY' in cmap
    offsets = list(map(int, re.findall(r'\d+', re.search(
        r'\b' + spec['codes'] + r'\[\]\s*=\s*\{(.*?)\};', source, re.S).group(1))))
    assert len(offsets) == declared and offsets == sorted(set(offsets))
    font = re.search(r'const lv_font_t ' + spec['fallback'] + r'\s*=\s*\{(.*?)\};', source, re.S).group(1)
    line = int(re.search(r'\.line_height=(\d+)', font).group(1))
    base = int(re.search(r'\.base_line=(\d+)', font).group(1))
    owned = {start + value for value in offsets}
    # The old 24px font delegates ASCII to Montserrat24, whose first real CMap
    # is FORMAT0_TINY range_start=32, range_length=95. Keep that existing path.
    available = owned | (set(range(32, 127)) if spec['fallback'] == 'clock_font_weather_24' else set())
    return available, owned, line, base, sha(data)


def font_source(size, spec, codes, glyphs, bitmap, line, base):
    prefix = f'hint_{size}'
    if codes:
        rows = ',\n'.join(','.join(map(str, bitmap[i:i + 32])) for i in range(0, len(bitmap), 32))
        desc = ','.join('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}' % row for row in glyphs)
        offsets = ','.join(str(cp - codes[0]) for cp in codes)
        body = f'''static const uint8_t {prefix}_bitmap[]={{
{rows}
}};
static const lv_font_fmt_txt_glyph_dsc_t {prefix}_glyphs[]={{{{0}},{desc}}};
static const uint16_t {prefix}_codes[]={{{offsets}}};
static const lv_font_fmt_txt_cmap_t {prefix}_map={{.range_start={codes[0]},.range_length={codes[-1]-codes[0]+1},.glyph_id_start=1,.unicode_list={prefix}_codes,.list_length={len(codes)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};
static const lv_font_fmt_txt_dsc_t {prefix}_dsc={{.glyph_bitmap={prefix}_bitmap,.glyph_dsc={prefix}_glyphs,.cmaps=&{prefix}_map,.cmap_num=1,.bpp={spec['bpp']},{'.stride=1,' if spec['bpp']==8 else ''}.bitmap_format=0}};
'''
    else:
        # LVGL 9.6 get_glyph_dsc_id returns 0 for cmap_num=0; its descriptor
        # callback returns false before accessing glyph_dsc. Normal font lookup
        # then resolves the old fallback. No CMap, bitmap or glyph array needed.
        body = f'''/* All requested {size}px characters are in the existing fallback. */
static const lv_font_fmt_txt_dsc_t {prefix}_dsc={{.cmap_num=0}};
'''
    static = '.static_bitmap=1,' if codes and spec['bpp'] == 8 else ''
    body += f'const lv_font_t clock_font_hint_{size}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={line},.base_line={base},{static}.dsc=&{prefix}_dsc,.fallback=&{spec["fallback"]}}};\n'
    return body


def generate():
    assert PILLOW == '12.3.0', 'Use the existing fixed Pillow 12.3.0 runtime'
    assert sha((ROOT / FONT_PATH).read_bytes()) == FONT_SHA, 'Pinned Noto source missing or changed'
    source = ['/* Generated by tools/generate-weather-hint-fonts.py.\n'
              ' * Noto Sans CJK SC Regular, SIL OFL 1.1; see OFL.txt and NotoSans-LICENSE.txt.\n'
              ' * S20 missing glyphs only; all pre-existing font assets are unchanged. */\n'
              '#include "weather_hint_fonts.h"\n'
              'extern const lv_font_t clock_font_weather_24,clock_font_28,clock_home_font_30;\n']
    records = {}
    inputs = {GENERATOR: sha((ROOT / GENERATOR).read_bytes().replace(b'\r\n', b'\n'))}
    for size, spec in SPECS.items():
        available, owned, line, base, digest = fallback_data(spec)
        required = {ord(ch) for text in spec['texts'] for ch in text if not ch.isspace()}
        codes = sorted(required - available)
        inputs['assets/application/' + spec['file']] = digest
        font = ImageFont.truetype(str(ROOT / FONT_PATH), size)
        bitmap, glyphs, alpha_hashes = bytearray(), [], {}
        for cp in codes:
            ch = chr(cp)
            x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
            w, h = x1-x0, y1-y0
            image = Image.new('L', (w, h))
            ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            pixels = image.tobytes()
            assert image.getbbox(), f'Empty new glyph U+{cp:04X}'
            assert line-base+y0 >= 0 and base-y1 >= 0, f'Glyph exceeds line: {ch}'
            glyphs.append((len(bitmap), round(font.getlength(ch)*16), w, h, x0, -y1))
            if spec['bpp'] == 4:
                bitmap.extend((pixels[i] >> 4) << 4 | (pixels[i+1] >> 4 if i+1 < len(pixels) else 0)
                              for i in range(0, len(pixels), 2))
            else:
                bitmap.extend(pixels)
            alpha_hashes[ch] = sha(pixels)
        assert not (set(codes) & available)
        assert required <= set(codes) | available
        source.append(font_source(size, spec, codes, glyphs, bitmap, line, base))
        records[str(size)] = {'font': f'clock_font_hint_{size}', 'fallback': spec['fallback'],
            'line_height': line, 'base_line': base, 'bpp': spec['bpp'] if codes else None,
            'characters': ''.join(map(chr, codes)), 'codepoints': codes, 'glyphs': len(codes),
            'bitmap_bytes': len(bitmap), 'fallback_own_glyphs': len(owned), 'requested_texts': spec['texts'],
            'new_glyph_source_alpha_sha256': alpha_hashes}
    header = ('#ifndef CLOCK_WEATHER_HINT_FONTS_H\n#define CLOCK_WEATHER_HINT_FONTS_H\n'
              '#include "lvgl.h"\n/* S20 supplements; original fallback metrics and assets are preserved. */\n'
              'extern const lv_font_t clock_font_hint_24,clock_font_hint_28,clock_font_hint_30;\n#endif\n')
    output = {'weather_hint_fonts.c': ''.join(source).encode(), 'weather_hint_fonts.h': header.encode()}
    record = {'version': 'S20', 'generator': GENERATOR, 'input_sha256': inputs,
        'font_source': 'Noto Sans CJK SC Regular', 'font_source_sha256': FONT_SHA,
        'font_url': 'https://raw.githubusercontent.com/googlefonts/noto-cjk/main/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf',
        'license': 'SIL OFL 1.1; OFL.txt and NotoSans-LICENSE.txt', 'pillow': PILLOW,
        'method': 'Missing direct-size glyphs only; 24px A4, 30px static A8; 28px zero-glyph fallback wrapper',
        'fonts': records, 'total_glyphs': sum(r['glyphs'] for r in records.values()),
        'total_bitmap_bytes': sum(r['bitmap_bytes'] for r in records.values()),
        'outputs': {name: {'bytes': len(data), 'sha256': sha(data)} for name, data in output.items()}}
    output['weather_hint_fonts.json'] = (json.dumps(record, ensure_ascii=False, indent=2) + '\n').encode()
    return output, record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reproduce all outputs in memory and compare; no writes')
    args = parser.parse_args()
    protected = {p.name: sha(p.read_bytes()) for p in ASSETS.iterdir()
                 if p.is_file() and p.name not in (*OUTPUT_NAMES, 'manifest.json')}
    output, record = generate()
    manifest_path = ASSETS / 'manifest.json'
    manifest = json.loads(manifest_path.read_bytes())
    prior_entries = {k: v for k, v in manifest.items() if k not in OUTPUT_NAMES}
    for name, data in output.items():
        entry = {'bytes': len(data), 'sha256': sha(data)}
        if args.check:
            assert (ASSETS / name).read_bytes() == data, name + ' differs'
            assert manifest.get(name) == entry, name + ' manifest differs'
        else:
            (ASSETS / name).write_bytes(data)
            manifest[name] = entry
    if not args.check:
        manifest_path.write_bytes((json.dumps(manifest, indent=2) + '\n').encode())
    assert prior_entries == {k: v for k, v in json.loads(manifest_path.read_bytes()).items() if k not in OUTPUT_NAMES}
    assert protected == {name: sha((ASSETS / name).read_bytes()) for name in protected}, 'Old asset changed'
    print(json.dumps({'checked': args.check, 'fonts': {s: {k: r[k] for k in
        ('font', 'characters', 'glyphs', 'bitmap_bytes', 'line_height', 'base_line', 'fallback')} for s, r in record['fonts'].items()},
        'total_bitmap_bytes': record['total_bitmap_bytes'], 'output_bytes': {n: len(d) for n, d in output.items()},
        'protected_old_assets_unchanged': len(protected)}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
